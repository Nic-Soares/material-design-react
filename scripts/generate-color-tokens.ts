// Generates src/tokens/color.css, the library's default color tokens
// (ADR-003), with Material Color Utilities configured as Material Theme
// Builder is — spec 2021, the Tonal Spot variant — from the M3 baseline source
// color. src/color/tokens.test.ts checks that parity against a real export.
//
//   npm run tokens
//
// Light and dark live in one value, light-dark(<light>, <dark>), resolved by
// the element's color-scheme: the browser follows the system setting, a
// data-theme attribute pins it, and nested themes work. Contrast levels are
// separate blocks, picked by data-contrast or prefers-contrast: more.

import { readFile, writeFile } from "node:fs/promises";
import {
  argbFromHex,
  Hct,
  SchemeTonalSpot,
} from "@material/material-color-utilities";
import {
  type ContrastLevel,
  colorRoles,
  colorVariable,
  contrastLevels,
  schemeColors,
} from "../src/color/tokens.ts";

const SOURCE_COLOR = "#6750A4";
const SPEC_VERSION = "2021";

const output = new URL("../src/tokens/color.css", import.meta.url);
const libraryPackage = new URL(
  "../node_modules/@material/material-color-utilities/package.json",
  import.meta.url,
);

function colors(isDark: boolean, contrast: ContrastLevel) {
  const source = Hct.fromInt(argbFromHex(SOURCE_COLOR));
  const scheme = new SchemeTonalSpot(
    source,
    isDark,
    contrastLevels[contrast],
    SPEC_VERSION,
  );
  return schemeColors(scheme);
}

function declarations(contrast: ContrastLevel): string {
  const light = colors(false, contrast);
  const dark = colors(true, contrast);
  return colorRoles
    .map((role) => {
      // Roles that don't change with the theme (the fixed ones) stay plain
      const value =
        light[role] === dark[role]
          ? light[role]
          : `light-dark(${light[role]}, ${dark[role]})`;
      return `  ${colorVariable(role)}: ${value};`;
    })
    .join("\n");
}

const { version } = JSON.parse(await readFile(libraryPackage, "utf8"));

const css = `/*
 * Generated by scripts/generate-color-tokens.ts — do not edit.
 * Material Color Utilities ${version}: spec ${SPEC_VERSION}, Tonal Spot,
 * source color ${SOURCE_COLOR}.
 */

/* Theme: the system setting by default; data-theme pins it, at any level */
:root {
  color-scheme: light dark;
}

[data-theme="light"] {
  color-scheme: light;
}

[data-theme="dark"] {
  color-scheme: dark;
}

/* Standard contrast */
:root,
[data-contrast="standard"] {
${declarations("standard")}
}

/* Medium contrast */
[data-contrast="medium"] {
${declarations("medium")}
}

/* High contrast: on request, or when the system asks for more contrast */
[data-contrast="high"] {
${declarations("high")}
}

@media (prefers-contrast: more) {
  :root:not([data-contrast]) {
${declarations("high").replace(/^ {2}/gm, "    ")}
  }
}
`;

await writeFile(output, css);
console.log(`Wrote ${output.pathname}`);
