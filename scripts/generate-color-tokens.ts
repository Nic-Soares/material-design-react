// Generates src/tokens/color.css, the library's default color tokens
// (ADR-003), with Material Color Utilities configured as Material Theme
// Builder is — spec 2021, the Tonal Spot variant — from the M3 baseline source
// color. src/color/tokens.test.ts checks that parity against a real export.
//
//   npm run tokens
//
// The CSS comes from schemeCss() (src/color/scheme.ts): light and dark in
// one light-dark() value per token, contrast levels as separate blocks.

import { readFile, writeFile } from "node:fs/promises";
import { schemeCss } from "../src/color/scheme.ts";

const SOURCE_COLOR = "#6750A4";

const output = new URL("../src/tokens/color.css", import.meta.url);
const libraryPackage = new URL(
  "../node_modules/@material/material-color-utilities/package.json",
  import.meta.url,
);

const { version } = JSON.parse(await readFile(libraryPackage, "utf8"));

// The same function the /color entry point exposes, so the defaults and a
// custom source color come from one code path (ADR-006)
const css = `/*
 * Generated by scripts/generate-color-tokens.ts — do not edit.
 * Material Color Utilities ${version}: spec 2021, Tonal Spot,
 * source color ${SOURCE_COLOR}.
 */

${schemeCss({ sourceColor: SOURCE_COLOR })}`;

await writeFile(output, css);
console.log(`Wrote ${output.pathname}`);
