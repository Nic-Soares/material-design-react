// Generates src/tokens/motion.css, the library's motion tokens (ADR-003).
//
//   npm run tokens
//
// M3 Expressive moves things with springs, defined by a damping ratio and a
// stiffness (Compose Material 3's ExpressiveMotionTokens and
// StandardMotionTokens: the Design Kit has no motion, so Google's code is the
// source). CSS has no springs, but linear() can follow any curve: each spring
// is simulated from 0 to 1 until it settles, and sampled into a linear()
// easing plus the duration it takes. Spatial springs may overshoot (position,
// size); effects springs don't (color, opacity).

import { writeFile } from "node:fs/promises";

type Spring = { damping: number; stiffness: number };
type SpringScheme = Record<string, Spring>;

// name → spring, as speed-kind (M3: md.sys.motion.spring.<speed>.<kind>)
const expressive: SpringScheme = {
  "fast-spatial": { damping: 0.6, stiffness: 800 },
  "default-spatial": { damping: 0.8, stiffness: 380 },
  "slow-spatial": { damping: 0.8, stiffness: 200 },
  "fast-effects": { damping: 1, stiffness: 3800 },
  "default-effects": { damping: 1, stiffness: 1600 },
  "slow-effects": { damping: 1, stiffness: 800 },
};

const standard: SpringScheme = {
  "fast-spatial": { damping: 0.9, stiffness: 1400 },
  "default-spatial": { damping: 0.9, stiffness: 700 },
  "slow-spatial": { damping: 0.9, stiffness: 300 },
  "fast-effects": { damping: 1, stiffness: 3800 },
  "default-effects": { damping: 1, stiffness: 1600 },
  "slow-effects": { damping: 1, stiffness: 800 },
};

// Done when it stays within 0.1% of the target
const SETTLE = 0.001;
const SAMPLES = 40;

/** Position of a unit-mass spring going from 0 to 1, at time t (seconds). */
export function springPosition({ damping, stiffness }: Spring, t: number) {
  const w0 = Math.sqrt(stiffness);
  if (damping < 1) {
    const wd = w0 * Math.sqrt(1 - damping * damping);
    const decay = Math.exp(-damping * w0 * t);
    return (
      1 - decay * (Math.cos(wd * t) + ((damping * w0) / wd) * Math.sin(wd * t))
    );
  }
  // Critically damped (damping = 1): no overshoot
  return 1 - Math.exp(-w0 * t) * (1 + w0 * t);
}

/** Seconds until the spring stays within SETTLE of the target. */
export function settleTime(spring: Spring): number {
  const step = 0.001;
  let lastOutside = 0;
  for (let t = 0; t < 5; t += step) {
    if (Math.abs(1 - springPosition(spring, t)) > SETTLE) lastOutside = t;
  }
  return lastOutside + step;
}

/** The spring as a CSS linear() easing and a duration in ms. */
export function springToCss(spring: Spring) {
  const duration = settleTime(spring);
  const points = Array.from({ length: SAMPLES + 1 }, (_, i) => {
    if (i === SAMPLES) return "1";
    const value = springPosition(spring, (duration * i) / SAMPLES);
    return Number(value.toFixed(3)).toString();
  });
  return {
    easing: `linear(${points.join(", ")})`,
    duration: `${Math.round(duration * 1000)}ms`,
  };
}

function springDeclarations(scheme: SpringScheme, indent = "  "): string {
  return Object.entries(scheme)
    .flatMap(([name, spring]) => {
      const { easing, duration } = springToCss(spring);
      return [
        `${indent}--md-sys-motion-spring-${name}-easing: ${easing};`,
        `${indent}--md-sys-motion-spring-${name}-duration: ${duration};`,
      ];
    })
    .join("\n");
}

// The M3 duration and easing tokens, for transitions that aren't springs
const durations = {
  short1: 50,
  short2: 100,
  short3: 150,
  short4: 200,
  medium1: 250,
  medium2: 300,
  medium3: 350,
  medium4: 400,
  long1: 450,
  long2: 500,
  long3: 550,
  long4: 600,
  "extra-long1": 700,
  "extra-long2": 800,
  "extra-long3": 900,
  "extra-long4": 1000,
};

const easings = {
  emphasized: "cubic-bezier(0.2, 0, 0, 1)",
  "emphasized-decelerate": "cubic-bezier(0.05, 0.7, 0.1, 1)",
  "emphasized-accelerate": "cubic-bezier(0.3, 0, 0.8, 0.15)",
  standard: "cubic-bezier(0.2, 0, 0, 1)",
  "standard-decelerate": "cubic-bezier(0, 0, 0, 1)",
  "standard-accelerate": "cubic-bezier(0.3, 0, 1, 1)",
  linear: "linear",
};

const css = `/*
 * Generated by scripts/generate-motion-tokens.ts — do not edit.
 *
 * Springs (M3 Expressive): each one as a linear() easing and the time it
 * takes to settle. Use both together:
 *   transition: transform var(--md-sys-motion-spring-default-spatial-duration)
 *     var(--md-sys-motion-spring-default-spatial-easing);
 * Expressive by default; data-motion="standard" switches to the calmer
 * standard scheme, on <html> or any element.
 */
:root {
${springDeclarations(expressive)}

${Object.entries(durations)
  .map(([name, ms]) => `  --md-sys-motion-duration-${name}: ${ms}ms;`)
  .join("\n")}

${Object.entries(easings)
  .map(([name, value]) => `  --md-sys-motion-easing-${name}: ${value};`)
  .join("\n")}
}

[data-motion="standard"] {
${springDeclarations(standard)}
}

[data-motion="expressive"] {
${springDeclarations(expressive)}
}
`;

const output = new URL("../src/tokens/motion.css", import.meta.url);
if (import.meta.main) {
  await writeFile(output, css);
  console.log(`Wrote ${output.pathname}`);
}
